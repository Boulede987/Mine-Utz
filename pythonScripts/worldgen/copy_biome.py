"""
copy_biome.py
=============
Interactively copies a biome JSON from any mod or vanilla jar into the
mineutz: namespace.

Outputs:
  1. Paxi datapack — data/mineutz/worldgen/biome/<new_name>.json
     Biome JSON copied verbatim; features/carvers referencing the original
     namespace still generate correctly.
  2. worldgen_data/mineutz_copies.json (created or updated) — picked up
     by merge_biome_parameters.py (step 21) so the new biome appears in
     the planner and dimension JSONs.

Note: biomes that rely on custom Java code for terrain shape (e.g. most
modded biomes) will look like the JSON copy but generate vanilla-ish terrain.
That is expected and not checked here.

After running: steps 21 → 22 → 23 → 24.
"""

import json
import sys
import zipfile
from pathlib import Path

sys.stdout.reconfigure(encoding='utf-8')

VANILLA_JAR    = (
    Path.home()
    / 'AppData' / 'Roaming' / 'PrismLauncher'
    / 'libraries' / 'com' / 'mojang' / 'minecraft'
    / '1.21.1' / 'minecraft-1.21.1-client.jar'
)
MODS_DIR       = Path('minecraft/mods')
MERGED_DIR     = Path('worldgen_data/merged')
COPIES_FILE    = Path('worldgen_data/mineutz_copies.json')
BIOME_DEST_DIR = Path('minecraft/config/paxi/datapacks/mineutz/data/mineutz/worldgen/biome')


def find_biome_in_jars(namespace: str, biome_name: str) -> bytes | None:
    """Search vanilla jar then mod jars for data/<namespace>/worldgen/biome/<name>.json."""
    jar_path = f'data/{namespace}/worldgen/biome/{biome_name}.json'

    candidates = []
    if namespace == 'minecraft':
        candidates = [VANILLA_JAR]
    else:
        candidates = sorted(MODS_DIR.glob('*.jar'))

    for jar_file in candidates:
        if not jar_file.exists():
            continue
        try:
            with zipfile.ZipFile(jar_file) as z:
                if jar_path in z.namelist():
                    print(f'  Found in {jar_file.name}')
                    return z.read(jar_path)
        except Exception:
            pass
    return None


def find_parameters(namespace: str, biome_name: str) -> dict | None:
    """Look up merged climate parameters for namespace:biome_name."""
    merged_file = MERGED_DIR / f'{namespace}.json'
    if not merged_file.exists():
        return None
    biome_id = f'{namespace}:{biome_name}'
    data = json.loads(merged_file.read_text(encoding='utf-8'))
    for dim_sections in data.get('dimensions', {}).values():
        for section in ['surface', 'underground', 'caves', 'deep']:
            for entry in dim_sections.get(section, []):
                if entry['biome'] == biome_id:
                    return entry['parameters']
    return None


def load_copies() -> dict:
    if COPIES_FILE.exists():
        return json.loads(COPIES_FILE.read_text(encoding='utf-8'))
    return {
        'namespace': 'mineutz',
        'note': 'Custom mineutz: biome copies. Generated by copy_biome.py.',
        'dimensions': {'minecraft:overworld': {'surface': []}},
    }


def main() -> None:
    print('=== Biome Copy Tool ===')
    print()

    namespace  = input('Source namespace (e.g. minecraft, biomesoplenty, biomeswevegone): ').strip()
    biome_name = input(f'Source biome name within {namespace}: ').strip()
    new_name   = input(f'New name under mineutz: ').strip()

    if not namespace or not biome_name or not new_name:
        print('Incomplete input — aborted.')
        raise SystemExit(1)

    source_id = f'{namespace}:{biome_name}'
    dest_id   = f'mineutz:{new_name}'
    print(f'\n  {source_id}  →  {dest_id}\n')

    # 1. Extract biome JSON
    raw = find_biome_in_jars(namespace, biome_name)
    if raw is None:
        print(f'ERROR: data/{namespace}/worldgen/biome/{biome_name}.json not found in any jar.')
        print('       Check namespace and biome name spelling.')
        raise SystemExit(1)

    BIOME_DEST_DIR.mkdir(parents=True, exist_ok=True)
    dest_path = BIOME_DEST_DIR / f'{new_name}.json'
    biome_json = json.loads(raw)
    dest_path.write_text(json.dumps(biome_json, indent=2), encoding='utf-8')
    print(f'  Wrote biome JSON → {dest_path}')

    # 2. Look up parameters
    params = find_parameters(namespace, biome_name)
    if params is None:
        print(f'\n  WARNING: no parameters for {source_id} in worldgen_data/merged/{namespace}.json.')
        print(f'  Biome JSON written but it won\'t appear in the planner or FilterRegion.')
        print(f'  If worldgen data hasn\'t been extracted for this namespace, run the relevant')
        print(f'  worldgen extraction step first, then re-run this script.')
        return

    # 3. Update copies source file
    copies = load_copies()
    surface = copies['dimensions']['minecraft:overworld']['surface']
    copies['dimensions']['minecraft:overworld']['surface'] = (
        [e for e in surface if e['biome'] != dest_id]
    )
    copies['dimensions']['minecraft:overworld']['surface'].append({
        'biome':      dest_id,
        'parameters': params,
    })
    COPIES_FILE.write_text(json.dumps(copies, indent=2), encoding='utf-8')
    print(f'  Updated {COPIES_FILE}')

    print(f'\nDone. Re-run steps 21 → 22 → 23 → 24 to propagate {dest_id}.')


main()
