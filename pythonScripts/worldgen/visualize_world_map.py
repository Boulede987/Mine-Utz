"""
worldgen/visualize_world_map.py
=================================
Renders a synthetic Minecraft-like world map showing the spatial biome distribution
that TerraBlender's nearest-neighbour algorithm would produce.

Each pixel represents one location in world space. The 6 climate values at that
location are generated by bandlimited noise that mirrors Minecraft's climate system:
long-wavelength temperature/humidity/continentalness give large smooth zones, while
short-wavelength weirdness creates rapid local variation (peaks vs valleys).

Usage:
    python pythonScripts/worldgen/visualize_world_map.py
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))
sys.stdout.reconfigure(encoding='utf-8')

try:
    import numpy as np
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import matplotlib.patches as mpatches
except ImportError as missing:
    print(f'ERROR: missing dependency — {missing}')
    print('Run: pip install numpy matplotlib')
    raise SystemExit(1)

from worldgen.biome_colour import build_rgb_image, compute_biome_coverage
from worldgen.biome_nearest_neighbour import (
    build_parameter_bounds, compute_nearest_entry_grid,
    load_overworld_entries, load_planner_overworld_biomes,
    MERGED_DATA_DIR,
)
from worldgen.biome_noise import generate_all_climate_maps, climate_maps_to_query_grid
from worldgen.constants import BIOME_PLANNER_FILE

MAP_WIDTH_PIXELS  = 512
MAP_HEIGHT_PIXELS = 512
MAP_SEED          = 42
LEGEND_MAX_BIOMES = 25

OUTPUT_PATH = Path('worldgen_data') / 'visualizations' / 'world_map.png'


def build_legend_patches(
    coverage:     dict[str, float],
    biome_colors: dict[str, tuple],
    max_biomes:   int,
) -> list:
    top_biomes = sorted(coverage, key=coverage.__getitem__, reverse=True)[:max_biomes]
    return [
        mpatches.Patch(color=biome_colors[b], label=f'{b}  ({coverage[b] * 100:.1f}%)')
        for b in top_biomes
    ]


def render_world_map(
    nearest_entry_grid: np.ndarray,
    entries:            list[dict],
    output_path:        Path,
) -> dict[str, float]:
    """Renders the biome map image and saves to output_path. Returns coverage dict."""
    image, biome_colors = build_rgb_image(nearest_entry_grid, entries)
    coverage            = compute_biome_coverage(nearest_entry_grid, entries)

    figure, (map_axis, legend_axis) = plt.subplots(
        1, 2, figsize=(18, 10), gridspec_kw={'width_ratios': [2, 1]}
    )
    map_axis.imshow(image, origin='upper', interpolation='nearest', aspect='equal')
    map_axis.set_title(
        f'Synthetic World Biome Map  ({MAP_WIDTH_PIXELS}×{MAP_HEIGHT_PIXELS} pixels, seed {MAP_SEED})',
        fontsize=12,
    )
    map_axis.axis('off')

    legend_patches = build_legend_patches(coverage, biome_colors, LEGEND_MAX_BIOMES)
    legend_axis.axis('off')
    legend_axis.legend(handles=legend_patches, loc='center left', fontsize=8,
                       title=f'Top {len(legend_patches)} biomes by coverage',
                       title_fontsize=9, frameon=True)
    unlabeled_count = max(0, len(coverage) - LEGEND_MAX_BIOMES)
    if unlabeled_count > 0:
        legend_axis.text(0.0, 0.02, f'+ {unlabeled_count} more biomes (unlabeled)',
                         transform=legend_axis.transAxes, fontsize=8, color='gray')

    figure.tight_layout()
    figure.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close(figure)
    return coverage


def print_coverage_report(coverage: dict[str, float]) -> None:
    print('\nBiome coverage on world map:')
    for biome, fraction in sorted(coverage.items(), key=lambda item: item[1], reverse=True):
        bar = '█' * int(fraction * 50)
        print(f'  {biome:<50} {fraction * 100:5.1f}%  {bar}')


def main() -> None:
    if not MERGED_DATA_DIR.exists():
        print('ERROR: worldgen_data/merged/ not found. Run merge_biome_parameters.py first.')
        raise SystemExit(1)
    if not BIOME_PLANNER_FILE.exists():
        print(f'ERROR: {BIOME_PLANNER_FILE} not found.')
        raise SystemExit(1)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    print('Loading planner overworld biomes...')
    planner_biomes = load_planner_overworld_biomes()
    print(f'  {len(planner_biomes)} biomes selected.')

    print('Loading overworld climate entries...')
    entries = load_overworld_entries(planner_biomes)
    print(f'  {len(entries)} total entries.')

    if not entries:
        print('No entries found — check merged data and planner selections.')
        raise SystemExit(1)

    lo_array, hi_array = build_parameter_bounds(entries)

    print('Generating climate noise maps...')
    climate_maps = generate_all_climate_maps(MAP_HEIGHT_PIXELS, MAP_WIDTH_PIXELS, MAP_SEED)
    query_grid   = climate_maps_to_query_grid(climate_maps)

    print(f'Computing nearest biome for {MAP_WIDTH_PIXELS}×{MAP_HEIGHT_PIXELS} pixels...')
    nearest_entry_grid = compute_nearest_entry_grid(lo_array, hi_array, query_grid)

    print('Rendering world map...')
    coverage = render_world_map(nearest_entry_grid, entries, OUTPUT_PATH)
    print(f'  → {OUTPUT_PATH}  ({len(coverage)} biomes visible)')

    print_coverage_report(coverage)


if __name__ == '__main__':
    main()
